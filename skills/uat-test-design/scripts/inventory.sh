#!/usr/bin/env bash
# uat-test-design Phase 1: リポジトリのインベントリ実測スクリプト
# 依存: bash / find / grep / wc / sort / awk のみ。出力は集計値だけで、ファイル本文は出力しない。
# 使い方: inventory.sh <repo-root>
set -u

ROOT="${1:-.}"
cd "$ROOT" || { echo "ERROR: cannot cd to $ROOT" >&2; exit 1; }

PRUNE=( \( -name node_modules -o -name .git -o -name dist -o -name build -o -name .next -o -name coverage -o -name .gradle -o -name target -o -name __pycache__ -o -name .venv \) -prune )

echo "=============================================="
echo "## 1. ドキュメント系ディレクトリの規模（2階層）"
echo "[閾値超過] = 100ファイル超 or md 30000行超（扱いは source-categories.md の規則で決定）/ [生成物] = 生成マーカー過半"
echo "=============================================="
printf "%-8s %-10s %-20s %s\n" "files" "lines(md)" "flag" "dir"
for top in docs doc documents spec specs design wiki; do
  [ -d "$top" ] || continue
  for d in "$top" "$top"/*/; do
    [ -d "$d" ] || continue
    d="${d%/}"
    files=$(find "$d" "${PRUNE[@]}" -o -type f -print 2>/dev/null | wc -l)
    lines=$(find "$d" "${PRUNE[@]}" -o -type f -name '*.md' -print 2>/dev/null | tr '\n' '\0' | xargs -0 -r cat 2>/dev/null | wc -l)
    flag="-"
    if [ "$files" -gt 100 ] || [ "$lines" -gt 30000 ]; then flag="[閾値超過]"; fi
    sampled=0; gen=0
    while IFS= read -r f; do
      sampled=$((sampled + 1))
      if head -5 "$f" 2>/dev/null | grep -qiE 'auto[- ]?generated|自動生成|generated by|作成者.*:.*(Claude|AI|Copilot)'; then gen=$((gen + 1)); fi
    done < <(find "$d" "${PRUNE[@]}" -o -type f -name '*.md' -print 2>/dev/null | head -50)
    if [ "$sampled" -gt 5 ] && [ $((gen * 2)) -gt "$sampled" ]; then flag="${flag}[生成物]"; fi
    printf "%-8s %-10s %-20s %s\n" "$files" "$lines" "$flag" "$d"
  done
done

echo ""
echo "=============================================="
echo "## 2. 情報源カテゴリの検出（パス名ヒントによる候補、各15件まで）"
echo "=============================================="
cat_hint() { # 浅いパス優先で表示（深い階層のタスク/実装記録ノイズを後ろへ）
  echo "--- $1"
  find . "${PRUNE[@]}" -o \( -type f -o -type d \) -print 2>/dev/null \
    | grep -iE "$2" | grep -vE '\.(png|jpe?g|svg|ico|pdf|lock)$' \
    | awk -F/ '{print NF"\t"$0}' | sort -n | cut -f2- | head -15
}
doc_hint() { # ドキュメントカテゴリ用: md とディレクトリのみ（ソースコードノイズを除去）
  echo "--- $1"
  find . "${PRUNE[@]}" -o \( -type d -o -type f -name '*.md' \) -print 2>/dev/null \
    | grep -iE "$2" | grep -vE '__tests__|/e2e/specs/' \
    | awk -F/ '{print NF"\t"$0}' | sort -n | cut -f2- | head -15
}
doc_hint "要件定義"          'requirement|要件|/prd|ears|user[-_ ]?stor'
doc_hint "機能仕様"          'docs?/spec|docs/.*feature|機能仕様|functional[-_]spec'
cat_hint "E2Eテスト"         '/e2e$|playwright\.config|cypress\.config'
cat_hint "画面・ルーティング"  'src/pages$|src/app$|src/routes$|src/views$'
doc_hint "外部連携"          'veritrans|stripe|paypay|payment|auth0|liff|oauth|webhook|notification'
doc_hint "セキュリティ資料"    'security|脆弱性|authz|診断|zap|pentest'
doc_hint "個別改修の記録"      'plans/|/adr|implements|/rfc'
doc_hint "運用・監視"         'operations?/|monitoring|runbook|incident|手順書|backup'
doc_hint "非機能試験の実績"    'load-?test|performance|/perf/|負荷試験'

echo ""
echo "=============================================="
echo "## 3. 既存テスト ID 体系の検出（採番衝突回避・自動化トレース設計用）"
echo "=============================================="
spec_list=$(find . "${PRUNE[@]}" -o -type f \( -name '*.spec.ts' -o -name '*.spec.js' -o -name '*.test.ts' -o -name '*.cy.ts' \) -print 2>/dev/null)
if [ -n "$spec_list" ]; then
  echo "spec ファイル数: $(printf '%s\n' "$spec_list" | wc -l)"
  echo "検出 ID（接頭辞別ユニーク数 上位10）:"
  printf '%s\n' "$spec_list" | tr '\n' '\0' \
    | xargs -0 -r grep -hoE '\b[A-Z]{1,4}(-[A-Z]{1,4})?-[0-9]+(-[0-9]+)?\b' 2>/dev/null \
    | sort -u | sed -E 's/-[0-9]+(-[0-9]+)?$//' | sort | uniq -c | sort -rn | head -10
else
  echo "spec/test ファイル未検出 → 自動化トレース列は全件「手動のみ」になる見込み"
fi

echo ""
echo "=============================================="
echo "## 3.5 単体テストの検出（カバレッジ判定の入力）"
echo "=============================================="
unit_list=$(find . "${PRUNE[@]}" -o -type f \( -name '*.test.ts' -o -name '*.test.tsx' -o -name '*.test.js' -o -name '*.test.jsx' -o -name '*Test.kt' -o -name '*Test.java' -o -name '*Spec.kt' -o -name '*_test.go' -o -name 'test_*.py' \) -print 2>/dev/null)
if [ -n "$unit_list" ]; then
  echo "単体テストファイル数: $(printf '%s\n' "$unit_list" | wc -l)"
  echo "所在（上位ディレクトリ別 件数、上位15）:"
  printf '%s\n' "$unit_list" | awk -F/ '{ if (NF>3) print $2"/"$3; else print $2 }' | sort | uniq -c | sort -rn | head -15
else
  echo "単体テスト未検出 → カバレッジ判定は E2E のみで行う（Unit は全件「なし」扱い）"
fi

echo ""
echo "=============================================="
echo "## 4. 画面数の近似（規模判定の入力）"
echo "=============================================="
find . "${PRUNE[@]}" -o -type d \( -name pages -o -name app -o -name routes -o -name views \) -print 2>/dev/null | grep -v '__tests__' | head -8 | while IFS= read -r p; do
  n=$(find "$p" -type f \( -name '*.tsx' -o -name '*.jsx' -o -name '*.vue' -o -name '*.svelte' \) ! -path '*api*' ! -name '_*' 2>/dev/null | wc -l)
  [ "$n" -gt 0 ] && echo "$p: $n"
done

echo ""
echo "## 完了。この出力を _inventory.md（情報源マップ）作成の入力とする。"
